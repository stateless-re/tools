import argparse
import ast
import base64
import hashlib
import io
import json
import re
import sys
import zipfile
from pathlib import Path
from typing import Any

from cryptography.hazmat.primitives.asymmetric.rsa import RSAPublicKey
from cryptography.hazmat.primitives.serialization import load_der_public_key

DAS_MARKER = "Disassembly generated by Pyarmor-Static-Unpack-1shot"
HEADER_RE = re.compile(rb"^# Pyarmor (\S+) \(([^)]*)\), (\d{6}), (?:([^,\n]+), )?(\S+)\s*$", re.M)
INSTR_RE = re.compile(r"^\s+\d+\s+([A-Z_]+)\s*(?:(\d+)(?::\s(.*))?)?\s*$")
OBJECT_RE = re.compile(r"^(\s*)Object Name:\s*(.*)$")
SECTION_RE = re.compile(r"^(\s*)\[([\w+ ]+)\]\s*$")
FROZEN_RE = re.compile(r"^frozenset\((.*)\)$", re.S)

WALLET_PATTERNS = {
    "btc": r"(bc1[a-z0-9]{25,87}|[13][a-km-zA-HJ-NP-Z1-9]{25,34})",
    "ltc": r"(ltc1[a-z0-9]{25,87}|[LM][a-km-zA-HJ-NP-Z1-9]{25,34})",
    "xmr": r"[48][0-9AB][1-9A-HJ-NP-Za-km-z]{93,105}",
    "eth": r"0x[a-fA-F0-9]{40}",
    "trx": r"T[1-9A-HJ-NP-Za-km-z]{33}",
    "xrp": r"r[1-9A-HJ-NP-Za-km-z]{24,34}",
    "doge": r"D[1-9A-HJ-NP-Za-km-z]{33}",
    "ton": r"[UE][Qq][A-Za-z0-9+/=_-]{46,48}",
    "sol": r"[1-9A-HJ-NP-Za-km-z]{32,44}",
}

INTERESTING_NAMES = (
    "DOMAINS",
    "VERIFIED_HASHES",
    "PUBLIC_KEY_B64",
    "FIXED_PASSWORD",
    "XMRIG_ZIP_NAME",
    "XMRIG_ZIP_HASH",
    "DEFENDER_EXCLUSION_PATH",
    "MONITORING_TOOLS",
    "GLOBAL_VERSION_FILE",
    "ONETIME_VERSION_FILE",
    "_DOWN_PATH_GUARDIAN",
    "_DOWN_PATH_INFAME",
)


def parse_literal(text: str) -> Any:
    frozen = FROZEN_RE.match(text)
    if frozen:
        return sorted(ast.literal_eval(frozen.group(1)))
    try:
        return ast.literal_eval(text)
    except (ValueError, SyntaxError):
        return text


def module_lines(lines: list[str]) -> list[str]:
    start = max(i for i, line in enumerate(lines) if line.rstrip() == "    [Disassembly]")
    return lines[start + 1 :]


def module_assignments(lines: list[str]) -> dict[str, Any]:
    stack: list[Any] = []
    names: dict[str, Any] = {}
    for line in module_lines(lines):
        match = INSTR_RE.match(line)
        if not match:
            continue
        op, arg, value = match.groups()
        if op in ("CACHE", "PRECALL", "NOP"):
            continue
        if op == "LOAD_CONST" and value is not None:
            stack.append(parse_literal(value))
        elif op in ("BUILD_LIST", "BUILD_SET") and arg == "0":
            stack.append([])
        elif op in ("LIST_EXTEND", "SET_UPDATE") and len(stack) >= 2:
            items = stack.pop()
            stack[-1] = list(stack[-1]) + list(items)
        elif op == "BUILD_CONST_KEY_MAP" and arg and len(stack) >= int(arg) + 1:
            keys = stack.pop()
            values = stack[-int(arg) :]
            del stack[-int(arg) :]
            stack.append(dict(zip(keys, values, strict=True)))
        elif op in ("STORE_NAME", "STORE_GLOBAL") and value and stack:
            names[value.strip()] = stack.pop()
            stack.clear()
        else:
            stack.clear()
    return names


def constants_by_object(lines: list[str]) -> dict[str, list[str]]:
    objects: dict[int, str] = {}
    sections: dict[int, str] = {}
    found: dict[str, list[str]] = {}
    for line in lines:
        stripped = line.strip()
        if not stripped:
            continue
        indent = len(line) - len(line.lstrip(" "))
        for key in [k for k in sections if k >= indent]:
            del sections[key]
        for key in [k for k in objects if k > indent]:
            del objects[key]
        obj = OBJECT_RE.match(line)
        if obj:
            objects[len(obj.group(1))] = obj.group(2).strip()
            continue
        section = SECTION_RE.match(line)
        if section:
            sections[len(section.group(1))] = section.group(2)
            continue
        if not stripped.startswith(("'", '"')):
            continue
        parents = [k for k in sections if k < indent]
        if not parents or sections[max(parents)] != "Constants":
            continue
        owners = [k for k in objects if k < indent]
        owner = objects[max(owners)] if owners else "<module>"
        value = parse_literal(stripped)
        if isinstance(value, str):
            found.setdefault(owner, []).append(value)
    return found


def classify_wallet(value: str) -> str | None:
    for coin, pattern in WALLET_PATTERNS.items():
        if re.fullmatch(pattern, value):
            return coin
    return None


def rsa_summary(b64: str) -> dict[str, Any]:
    der = base64.b64decode(b64)
    key = load_der_public_key(der)
    if not isinstance(key, RSAPublicKey):
        return {"spki_sha256": hashlib.sha256(der).hexdigest()}
    numbers = key.public_numbers()
    return {
        "bits": key.key_size,
        "e": numbers.e,
        "n_prefix": f"{numbers.n:x}"[:32],
        "spki_sha256": hashlib.sha256(der).hexdigest(),
    }


def parse_das(path: Path, text: str) -> dict[str, Any]:
    lines = text.splitlines()
    module = re.search(r"File Name: <frozen ([^>]+)>", text)
    names = module_assignments(lines)
    consts = constants_by_object(lines)
    record: dict[str, Any] = {"file": str(path), "kind": "pyarmor-1shot-das"}
    record["module"] = module.group(1) if module else None
    record["config"] = {k: names[k] for k in INTERESTING_NAMES if k in names}
    domains = names.get("DOMAINS")
    if domains:
        record["c2"] = [f"{host}:{port}" for host, port in domains]
    if "PUBLIC_KEY_B64" in names:
        record["task_signing_key"] = rsa_summary(names["PUBLIC_KEY_B64"])
    if "FIXED_PASSWORD" in names:
        seed = str(names["FIXED_PASSWORD"]).encode()
        record["screenshot_xor_key"] = hashlib.sha256(seed).hexdigest()
    wallets = []
    for value in consts.get("monitor_clipboard", []):
        coin = classify_wallet(value)
        if coin:
            wallets.append({"coin": coin, "address": value})
    if wallets:
        record["clipper_wallets"] = wallets
    all_strings = {s for values in consts.values() for s in values}
    record["endpoints"] = sorted(
        s for s in all_strings if re.fullmatch(r"/[A-Za-z0-9_./\-]+/?", s) and len(s) > 1
    )
    record["urls"] = sorted(s for s in all_strings if re.match(r"https?://\S+$", s))
    return record


def xmrig_config(data: bytes) -> dict[str, Any] | None:
    start = data.find(b'"pools"')
    if start < 0:
        return None
    anchor = data.rfind(b'"api"', 0, start)
    if anchor < 0:
        return None
    begin = data.rfind(b"{", 0, anchor)
    depth = 0
    for end in range(begin, len(data)):
        if data[end] == 0x7B:
            depth += 1
        elif data[end] == 0x7D:
            depth -= 1
            if depth == 0:
                break
    try:
        config = json.loads(data[begin : end + 1])
    except ValueError:
        return None
    pools = [
        {k: pool.get(k) for k in ("url", "user", "coin", "algo", "rig-id", "tls")}
        for pool in config.get("pools", [])
    ]
    return {
        "config_offset": begin,
        "worker_id": config.get("api", {}).get("worker-id"),
        "donate_level": config.get("donate-level"),
        "max_threads_hint": config.get("cpu", {}).get("max-threads-hint"),
        "pools": pools,
    }


def parse_blob(name: str, data: bytes) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    sha256 = hashlib.sha256(data).hexdigest()
    if data[:2] == b"PK":
        with zipfile.ZipFile(io.BytesIO(data)) as archive:
            for member in archive.namelist():
                if member.lower().endswith(("xmrig.exe", "config.json")):
                    for record in parse_blob(f"{name}!{member}", archive.read(member)):
                        records.append(record)
        return records
    header = HEADER_RE.search(data[:4096])
    if header and b"__pyarmor__" in data[:8192]:
        version, edition, serial, product, stamp = (
            g.decode() if g else None for g in header.groups()
        )
        records.append(
            {
                "file": name,
                "sha256": sha256,
                "kind": "pyarmor-script",
                "pyarmor_version": version,
                "edition": edition,
                "serial": serial,
                "product": product,
                "obfuscated_at": stamp,
                "trial_key": serial == "000000",
            }
        )
        return records
    config = xmrig_config(data)
    if config:
        kind = "xmrig-embedded-config" if data[:2] == b"MZ" else "xmrig-config"
        records.append({"file": name, "sha256": sha256, "kind": kind, **config})
    return records


def parse_path(path: Path) -> list[dict[str, Any]]:
    data = path.read_bytes()
    head = data[:4096].decode("utf-8", "replace")
    if DAS_MARKER in head:
        return [parse_das(path, data.decode("utf-8", "replace"))]
    records = parse_blob(str(path), data)
    if not records:
        raise ValueError("no Armorsteal script, 1shot disassembly or XMRig config found")
    return records


def expand(paths: list[str]) -> list[Path]:
    result: list[Path] = []
    for item in paths:
        path = Path(item)
        if path.is_dir():
            result.extend(sorted(p for p in path.rglob("*") if p.is_file()))
        else:
            result.append(path)
    return result


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Extract Armorsteal configuration from Pyarmor-Static-Unpack-1shot "
        "disassembly (.1shot.das), Pyarmor script headers, and XMRig configs or binaries."
    )
    parser.add_argument("paths", nargs="+", help="files or directories")
    parser.add_argument(
        "--das-only", action="store_true", help="in directories, read only *.1shot.das files"
    )
    args = parser.parse_args()
    failed = False
    output = []
    for path in expand(args.paths):
        if args.das_only and not path.name.endswith(".1shot.das"):
            continue
        try:
            output.extend(parse_path(path))
        except (OSError, ValueError, zipfile.BadZipFile) as error:
            failed = True
            output.append({"file": str(path), "error": str(error)})
    json.dump(output, sys.stdout, indent=2, default=list)
    sys.stdout.write("\n")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
